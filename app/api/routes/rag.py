class RAGTelemetryResponse(BaseModel):
    """Per-process personalization counters surfaced for the UX panel."""

    queries_total: int = Field(
        ..., description="Every call to LocalRAGRetriever.retrieve that produced a hit OR an empty result.",
    )
    queries_personalized: int = Field(
        ...,
        description="Subset of ``queries_total`` where ``personalize`` was on AND at least one "
                    "candidate received a non-zero personalization bonus.",
    )
    queries_reordered: int = Field(
        ...,
        description="Subset of ``queries_personalized`` where the post-rerank top-k order "
                    "differed from the pure cosine baseline.",
    )
    queries_promoted_to_top: int = Field(
        ...,
        description="Subset of ``queries_reordered`` where the #1 result changed identity \u2014 "
                    "the strongest signal that personalization is materially affecting the user.",
    )
    signal_lookups_failed: int = Field(
        ...,
        description="Counter of personalization queries where loading the signals DB raised. "
                    "Always > 0 indicates a disk-level fault; the ranker continued without signals.",
    )


class RAGTelemetryResetResponse(BaseModel):
    reset: bool


class RAGReindexRequest(BaseModel):
    max_items: int = Field(
        500, ge=1, le=5_000,
        description="Upper bound on the number of items embedded in this call. "
                    "Caller polls again to drain the remainder.",
    )
    batch_size: int = Field(
        16, ge=1, le=128,
        description="Number of texts sent per embedding API call.",
    )


class RAGReindexResponse(BaseModel):
    scanned: int = Field(..., description="Items pulled from the store for this run.")
    embedded: int = Field(..., description="Items whose embedding was successfully persisted.")
    skipped: int = Field(
        0,
        description="Items that cannot be embedded (e.g. empty title and body). "
                    "When ``embedded == 0`` and ``skipped == scanned`` the caller "
                    "should stop polling \u2014 the remaining rows will never make progress.",
    )
    errors: int = Field(..., description="Items that failed embedding or persistence.")
    remaining: int = Field(
        ...,
        description="Items that are still missing an embedding OR pinned to a prior model "
                    "(would be picked up by the next call).",
    )


class RAGReindexStartRequest(BaseModel):
    batch_size: int = Field(
        16, ge=1, le=128,
        description="Number of texts sent per embedding API call.",
    )


class RAGReindexJobStatus(BaseModel):
    id: str
    status: str = Field(
        ..., description="One of: queued, running, done, cancelled, error.",
    )
    scanned: int
    embedded: int
    skipped: int
    errors: int
    total: int
    batch_size: int
    started_at: Optional[float]
    finished_at: Optional[float]
    detail: Optional[str] = None


class RAGReindexJobsResponse(BaseModel):
    jobs: List[RAGReindexJobStatus]


