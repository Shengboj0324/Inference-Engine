def _retriever() -> LocalRAGRetriever:
    return get_rag_retriever()


def _embedder() -> LocalEmbeddingProvider:
    """Resolve the embedder used by the backfill route.

    Delegates to the same provider the retriever already holds so the
    backfill respects the same BYOK / permission / scrubbing contract as
    the chat-time path.  Exposed as a module-level seam so tests can
    inject a fake without monkey-patching :class:`LocalRAGRetriever`.
    """
    return _retriever()._embedder  # type: ignore[attr-defined]


def _store() -> ContentStore:
    return get_content_store()


@router.get("/status", response_model=RAGStatusResponse)
async def get_status() -> RAGStatusResponse:
    r = _retriever()
    # The embedder may be unreachable (no key / denied permission); we
    # still expose ``stale_count`` based on missing embeddings so the UI
    # can render "X items pending" even before the user grants the key.
    current_version: Optional[str] = None
    try:
        current_version = _embedder().model
    except Exception:  # noqa: BLE001 - status must never raise
        current_version = None
    return RAGStatusResponse(
        available=r.is_available(),
        indexed_count=r.indexed_count(),
        current_version=current_version,
        stale_count=_store().count_stale_embeddings(current_version),
    )


@router.post("/search", response_model=RAGSearchResponse)
async def search(request: RAGSearchRequest) -> RAGSearchResponse:
    from app.core.models import SourcePlatform  # local import keeps this route cheap at import time

    platforms = None
    if request.platforms:
        try:
            platforms = [SourcePlatform(p) for p in request.platforms]
        except ValueError as exc:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=f"unknown platform value: {exc}",
            )
    r = _retriever()
    snippets: List[RetrievedSnippet] = await r.retrieve(
        request.query, k=request.k, platforms=platforms, min_score=request.min_score,
    )
    return RAGSearchResponse(
        query=request.query,
        snippets=[RAGSnippet(**s.to_dict()) for s in snippets],
    )


async def _run_reindex_batches(
    *,
    store: ContentStore,
    embedder: LocalEmbeddingProvider,
    current_version: Optional[str],
    max_items: int,
    batch_size: int,
    progress: Optional[ReindexJob] = None,
    should_cancel: Optional[callable] = None,  # type: ignore[valid-type]
) -> tuple[int, int, int, int]:
    """Drain stale embeddings in batches.  Shared by sync + background paths.

    Returns ``(scanned, embedded, skipped, errors)``.  When ``progress`` is
    provided each batch updates its counters in-place so a UI poll can see
    incremental progress.  When ``should_cancel`` returns True the loop
    exits cleanly between batches.
    """
    pending = store.list_stale_embeddings(current_version, limit=max_items)
    scanned = len(pending)
    if progress is not None:
        progress.total = max(progress.total, scanned)
    embedded = 0
    errors = 0
    skipped = 0
    for offset in range(0, scanned, batch_size):
        if should_cancel is not None and should_cancel():
            break
        chunk = pending[offset: offset + batch_size]
        # Filter out rows with no usable text — they cannot be embedded
        # and would otherwise be re-pulled forever, leaving the UI
        # convinced there is work remaining.
        prepared = [(cid, ((title or "") + "\n" + (raw or "")).strip())
                    for cid, title, raw in chunk]
        usable = [(cid, text) for cid, text in prepared if text]
        skipped += len(prepared) - len(usable)
        if not usable:
            if progress is not None:
                progress.scanned += len(prepared)
                progress.skipped = skipped
            continue
        try:
            vectors = await embedder.embed_batch([t for _, t in usable])
        except EmbeddingUnavailable as exc:
            # Permission revoked mid-run: abort cleanly with what we got.
            logger.warning("reindex aborted: %s", exc)
            errors += len(usable)
            break
        except Exception:  # noqa: BLE001 - per-batch isolation
            logger.exception("reindex batch failed (offset=%d)", offset)
            errors += len(usable)
            if progress is not None:
                progress.scanned += len(prepared)
                progress.errors = errors
            continue
        if len(vectors) != len(usable):
            logger.warning(
                "reindex batch returned %d vectors for %d inputs; skipping",
                len(vectors), len(usable),
            )
            errors += len(usable)
            if progress is not None:
                progress.scanned += len(prepared)
                progress.errors = errors
            continue
        for (cid, _text), vec in zip(usable, vectors):
            try:
                if store.set_embedding(cid, vec, version=current_version):
                    embedded += 1
                else:
                    errors += 1
            except Exception:  # noqa: BLE001 - per-item isolation
                logger.exception("reindex persist failed for %s", cid)
                errors += 1
        if progress is not None:
            progress.scanned += len(prepared)
            progress.embedded = embedded
            progress.errors = errors
            progress.skipped = skipped
    return scanned, embedded, skipped, errors


@router.post("/reindex", response_model=RAGReindexResponse)
async def reindex(request: RAGReindexRequest) -> RAGReindexResponse:
    """Embed up to ``max_items`` rows that currently lack an embedding.

    Returns 409 when the RAG layer is not currently available — operator
    actions must fail loudly so the UI can surface a "configure key /
    grant permission" CTA instead of silently doing nothing.
    """
    retriever = _retriever()
    if not retriever.is_available():
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail="RAG layer unavailable: configure an embedding key and "
                   "grant USE_LLM_KEY before running reindex.",
        )
    store = _store()
    embedder = _embedder()
    # ``model`` may raise on a misconfigured embedder; treat as no
    # version so the selector falls back to "missing only".
    try:
        current_version: Optional[str] = embedder.model
    except Exception:  # noqa: BLE001
        current_version = None
    scanned, embedded, skipped, errors = await _run_reindex_batches(
        store=store,
        embedder=embedder,
        current_version=current_version,
        max_items=request.max_items,
        batch_size=request.batch_size,
    )
    return RAGReindexResponse(
        scanned=scanned,
        embedded=embedded,
        skipped=skipped,
        errors=errors,
        remaining=store.count_stale_embeddings(current_version),
    )


